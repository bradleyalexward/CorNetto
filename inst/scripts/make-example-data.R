## This script documents the synthetic example assets shipped with
## CorNetto in inst/extdata. The files are hand-curated toy data used only
## for package examples, tests, and the vignette; they are not derived from
## an external experiment or downloaded resource.
##
## Files:
## - example_sample_data.csv: 8 samples split into Recovered and PASC groups.
## - example_protein_abundance.csv: normalized abundance values for 5 proteins.
## - example_transcript_abundance.csv: normalized abundance values for 5
##   transcripts.
## - example_metabolite_abundance.csv: normalized abundance values for 4
##   metabolites.
## - example_knowledge_network.csv: prior edges spanning within-omic and
##   cross-omic relationships plus one drug-target edge.
## - example_seed_nodes.txt: a small seed-node set for focused-network examples.
##
## The example values are deterministic and intentionally small so that all
## package examples and tests run quickly on Bioconductor build machines.
